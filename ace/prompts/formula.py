# ---------------------------------------------------------------------------------------
# Curator
#
# DELTA 1: the `refines` field, required-but-nullable, in the field list, the ADD operation
# and the response example. Upstream's curator emits only type/section/content. `refines` is
# the graph arm's only capability -- it is the independent variable of this experiment --
# so without it the graph arm is a guaranteed null by construction. Required-but-nullable
# rather than optional because a model given an optional key simply omits it: measured on
# MBPP, 0 of 24 curator calls emitted `refines` while it was optional, not even as null.
# Shown identically to all three arms; the text arm ignores the field, which keeps the arms
# differing in one place only.
# ---------------------------------------------------------------------------------------

_REFINES_FIELD = """    - refines: the bullet_id of an existing playbook entry that this new entry supersedes, copied verbatim from the Current Playbook, for example "calc-00005", or null if it supersedes nothing. This field is required on every ADD; scan the Current Playbook for an entry covering the same ground before deciding, and use null when there is none."""

