"""Prompts for the finance tasks (`formula`, `finer`).

These are the ACE authors' own prompts, taken from the upstream repository, so a run here
is a replication rather than a reimplementation. Two changes were necessary and are marked
DELTA below; everything else is verbatim, including wording this fork would otherwise have
tightened.

The generator prompt's four placeholders were converted from positional `{}` to named
fields. Upstream orders them playbook -> reflection -> question -> context, while
`Generator.generate` supplies question, context, playbook, reflection; formatting the
upstream text positionally would put the question under the "Playbook" heading and the
playbook under "Question", silently, in every call. Naming them fixes the binding without
touching a word of the prompt. See `PromptSet.format_generator` in `ace/prompts/__init__.py`.
"""

